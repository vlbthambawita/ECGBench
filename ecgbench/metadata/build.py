# --------------------------------------------------------------------------- parsing


def parse_count(text: object) -> int | None:
    """Parse a catalogue count display string into an int, or ``None``.

    Only a bare integer, with or without thousands separators, is accepted.
    Anything qualified — an approximation, a unit word, a parenthetical, a
    range, a dash — is a statement the catalogue author chose to make, and
    flattening it to a number would lose the qualification.
    """
    if text is None:
        return None
    if isinstance(text, bool):
        return None
    if isinstance(text, int):
        return text
    match = _PLAIN_INTEGER.match(str(text))
    if not match:
        return None
    return int(match.group(1).replace(",", ""))


def _section_text(sections: list | None) -> str:
    """Flatten a catalogue page's ``sections:`` list to searchable text."""
    parts: list[str] = []
    for section in sections or []:
        if not isinstance(section, dict):
            continue
        title = section.get("title")
        if title:
            parts.append(str(title))
        kind = section.get("type")
        if kind == "description":
            parts.append(str(section.get("body", "")))
        elif kind == "table":
            parts.append(" ".join(str(h) for h in section.get("headers", []) or []))
            for row in section.get("rows", []) or []:
                parts.append(" ".join(str(cell) for cell in (row or [])))
            if section.get("footnote"):
                parts.append(str(section["footnote"]))
        elif kind == "links":
            for item in section.get("items") or section.get("links") or []:
                if isinstance(item, dict):
                    parts.append(" ".join(str(v) for v in item.values() if isinstance(v, str)))
                else:
                    parts.append(str(item))
        # ``code`` sections are examples, not description; their title suffices.
    return "\n".join(p.strip() for p in parts if p and p.strip())


# --------------------------------------------------------------------------- sources


def _catalogue_source_path(entry: CatalogueEntry) -> str:
    directory = catalogue._datasets_dir()
    path = directory / f"{entry.slug}.md"
    try:
        return path.relative_to(_REPO_ROOT).as_posix()
    except ValueError:
        return f"{directory.name}/{entry.slug}.md"


def _config_source_path(slug: str) -> str:
    return (_CONFIGS_DIR / f"{slug}.yaml").relative_to(_REPO_ROOT).as_posix()


def _has_custom_label_module(slug: str) -> bool:
    return (_LABELS_DIR / f"{slug}.py").is_file()


def _labels_available(config: DatasetConfig) -> bool:
    if config.labels is not None and config.labels.available is False:
        return False
    if _has_custom_label_module(config.slug):
        return True
    # Declarative labels: ``_load_declarative`` needs a source CSV and a join
    # column; ``columns: null`` there means "every other column", not "none".
    spec = config.labels
    return bool(spec is not None and spec.source_csv and spec.join_column)


def _field_metas(config: DatasetConfig) -> tuple[FieldMeta, ...]:
    """Declared label fields, read statically so the build never imports pandas.

    ``FIELDS`` in ``ecgbench/labels/<slug>.py`` is parsed with ``ast``; a
    declarative dataset answers from its ``labels:`` block. A module without a
    declaration yields no fields — the field inventory is being filled in
    per-dataset batches, and a missing declaration is not an error here.
    """
    from ecgbench.labels._fields import fields_for

    return tuple(FieldMeta(**f.to_dict()) for f in fields_for(config, static=True))


def _implementation_state(config: DatasetConfig | None) -> str:
    if config is None:
        return "catalogue_only"
    if not _labels_available(config):
        return "config"
    if config.publish_fold_csvs:
        return "published"
    return "config_labels"


def _catalogue_facts(entry: CatalogueEntry) -> list[Fact]:
    prov = Provenance(source="catalogue", source_path=_catalogue_source_path(entry))
    raw = entry.raw
    pairs: list[tuple[str, object]] = [
        ("name", entry.name),
        ("category", entry.category),
        ("status", entry.status),
        ("url", raw.get("source_url") or entry.url or None),
        ("url_label", entry.url_label),
        ("format", entry.format),
        ("records", entry.records),
        ("patients", entry.patients),
        ("access", entry.access),
        ("license", entry.license),
        ("origin_institution", entry.origin_institution),
        ("origin_country", entry.origin_country),
        ("leads", entry.leads),
        ("paper_title", entry.paper_title),
        ("paper_doi", entry.paper_doi),
        ("search_keywords", entry.search_keywords),
        ("config_slug", entry.config_slug),
    ]
    return [Fact(key, value, prov) for key, value in pairs if value not in (None, "")]


def _config_facts(config: DatasetConfig) -> list[Fact]:
    prov = Provenance(source="config", source_path=_config_source_path(config.slug))
    pairs: list[tuple[str, object]] = [
        ("name", config.name),
        ("version", config.version),
        ("url", config.url),
        ("download_url", config.download_url),
        ("license", config.license),
        ("doi", config.doi),
        ("signal_format", config.signal_format),
        ("leads", config.leads),
        ("sampling_rates", list(config.sampling_rates)),
        ("default_sampling_rate", config.default_sampling_rate),
        ("duration_seconds", config.duration_seconds),
        ("signal_units", config.signal_units),
        ("n_folds", config.n_folds),
        ("has_predefined_splits", config.has_predefined_splits),
        ("record_id_column", config.record_id_column),
        ("patient_id_column", config.patient_id_column),
        ("label_column", config.label_column),
        ("label_format", config.label_format),
        ("publish_fold_csvs", config.publish_fold_csvs),
    ]
    return [Fact(key, value, prov) for key, value in pairs if value not in (None, "")]


def _signal_meta(config: DatasetConfig) -> SignalMeta:
    return SignalMeta(
        format=config.signal_format,
        leads=int(config.leads),
        lead_names=tuple(config.lead_names) if config.lead_names else None,
        alternate_lead_names=(
            {int(k): tuple(v) for k, v in config.alternate_lead_names.items()}
            if config.alternate_lead_names
            else None
        ),
        record_lead_layouts=(
            tuple(tuple(layout) for layout in config.record_lead_layouts)
            if config.record_lead_layouts
            else None
        ),
        sampling_rates=tuple(int(r) for r in config.sampling_rates),
        default_sampling_rate=int(config.default_sampling_rate),
        duration_seconds=float(config.duration_seconds),
        units=config.signal_units,
        unit_scale=float(config.signal_unit_scale),
        zero_padded_identifiers=bool(config.zero_padded_identifiers),
    )


def _split_meta(config: DatasetConfig) -> SplitMeta:
    predefined = None
    if config.has_predefined_splits and config.predefined_splits is not None:
        predefined = config.predefined_splits.column
    return SplitMeta(
        n_folds=int(config.n_folds),
        predefined_column=predefined,
        has_patient_id=config.patient_id_column is not None,
        record_id_column=config.record_id_column or None,
    )


def _access_meta(entry: CatalogueEntry, config: DatasetConfig | None) -> AccessMeta:
    license_url: str | None = None
    license_text: str | None = entry.license or None
    if config is not None and config.license:
        if _URL.match(config.license):
            license_url = config.license
        elif license_text is None:
            license_text = config.license
    url = entry.raw.get("source_url") or entry.url
    if config is not None and config.url:
        url = config.url
    return AccessMeta(
        access=entry.access,
        license_text=license_text,
        license_url=license_url,
        url=url,
        download_url=config.download_url if config is not None else None,
        publish_fold_csvs=bool(config.publish_fold_csvs) if config is not None else False,
        no_publish_reason=(config.no_publish_reason or "") if config is not None else "",
    )


def _paper_doi(entry: CatalogueEntry, config: DatasetConfig | None) -> str | None:
    if entry.paper_doi:
        return entry.paper_doi
    if config is not None and config.doi:
        doi = config.doi.strip()
        return doi if _URL.match(doi) else f"https://doi.org/{doi}"
    return None


def _description(entry: CatalogueEntry, config: DatasetConfig | None) -> str:
    if config is not None and config.description:
        return config.description.strip()
    for section in entry.raw.get("sections") or []:
        if isinstance(section, dict) and section.get("type") == "description":
            return str(section.get("body", "")).strip()
    return ""


def _prose(entry: CatalogueEntry, config: DatasetConfig | None) -> str:
    parts = [_section_text(entry.raw.get("sections"))]
    if config is not None:
        parts.append(config.description or "")
        parts.append(config.citation or "")
        parts.append(" ".join(config.croissant.keywords))
        parts.append(config.croissant.rai_data_collection or "")
        parts.append(config.croissant.rai_data_biases or "")
        parts.append(config.croissant.rai_personal_sensitive_info or "")
        parts.extend(creator.name for creator in config.creators)
    return "\n".join(p.strip() for p in parts if p and p.strip())


def _aliases(entry: CatalogueEntry, config: DatasetConfig | None) -> tuple[str, ...]:
    candidates = [entry.slug]
    if config is not None:
        candidates.append(config.slug)
    candidates.append(entry.name)
    if config is not None and config.name:
        candidates.append(config.name)
    seen: set[str] = set()
    out: list[str] = []
    for alias in candidates:
        if alias and alias.casefold() not in seen:
            seen.add(alias.casefold())
            out.append(alias)
    return tuple(out)


# --------------------------------------------------------------------------- build


class _CountParser:
    """``parse_count`` that logs each unparsed display string once."""

    def __init__(self) -> None:
        self._reported: set[str] = set()

    def __call__(self, dataset_id: str, key: str, text: str) -> int | None:
        value = parse_count(text)
        if value is None and text.strip() and text not in self._reported:
            self._reported.add(text)
            logger.info(
                "%s: %s=%r is not a plain integer; kept as display text", dataset_id, key, text
            )
        return value


def build_model() -> tuple[DatasetMeta, ...]:
    """Merge every catalogue entry with its config into ``DatasetMeta`` records.

    Returns:
        One record per catalogue entry, sorted by ``dataset_id``.

    Raises:
        MetadataBuildError: a declared ``config_slug`` names no YAML, a config is
            claimed by no catalogue entry, two entries claim one config, an alias
            is shared by two datasets, or a config fails to load.
    """
    entries = catalogue._load()
    available = set(list_available_configs())
    problems: list[str] = []

    claims: dict[str, list[str]] = {}
    for entry in entries:
        if entry.config_slug:
            claims.setdefault(entry.config_slug, []).append(entry.slug)
    for slug, owners in sorted(claims.items()):
        if slug not in available:
            problems.append(
                f"{owners[0]}: config_slug={slug!r} names no config in {_CONFIGS_DIR.name}/"
            )
        if len(owners) > 1:
            problems.append(
                f"config {slug!r} is claimed by {len(owners)} entries: {sorted(owners)}"
            )
    for slug in sorted(available - set(claims)):
        problems.append(
            f"config {slug!r} is claimed by no catalogue entry (add config_slug to one)"
        )

    configs: dict[str, DatasetConfig] = {}
    for slug in sorted(available & set(claims)):
        try:
            configs[slug] = load_config(slug)
        except (ValueError, FileNotFoundError, KeyError) as exc:  # pragma: no cover
            problems.append(f"config {slug!r} does not load: {exc}")

    dataset_ids = {
        entry.slug: (entry.config_slug if entry.config_slug in configs else entry.slug)
        for entry in entries
    }

    counts = _CountParser()
    model: list[DatasetMeta] = []
    for entry in entries:
        config = configs.get(entry.config_slug) if entry.config_slug else None
        dataset_id = dataset_ids[entry.slug]
        facts = _catalogue_facts(entry) + (_config_facts(config) if config else [])
        state = _implementation_state(config)
        assert state in IMPLEMENTATION_STATES
        relations = tuple(
            RelationMeta(
                target=dataset_ids.get(link.slug, link.slug),
                relation=link.relation,
                shares_records=link.shares_records,
                verified=link.verified,
                note=link.note,
                derived=link.derived,
            )
            for link in entry.related
        )
        model.append(
            DatasetMeta(
                dataset_id=dataset_id,
                aliases=_aliases(entry, config),
                name=entry.name,
                category=entry.category,
                status=entry.status,
                implementation_state=state,
                version=config.version if config else None,
                description=_description(entry, config),
                paper_title=entry.paper_title or None,
                paper_doi=_paper_doi(entry, config),
                citation=(config.citation or "").strip() if config else "",
                origin_institution=entry.origin_institution,
                origin_country=entry.origin_country,
                search_keywords=entry.search_keywords or "",
                records=counts(dataset_id, "records", entry.records),
                patients=counts(dataset_id, "patients", entry.patients),
                records_display=entry.records,
                patients_display=entry.patients,
                signal=_signal_meta(config) if config else None,
                access=_access_meta(entry, config),
                split=_split_meta(config) if config else None,
                relations=relations,
                fields=_field_metas(config) if config else (),
                facts=tuple(facts),
                prose=_prose(entry, config),
            )
        )

    model.sort(key=lambda m: m.dataset_id)
    try:
        AliasIndex(model)
    except ValueError as exc:
        problems.append(str(exc))

    if problems:
        raise MetadataBuildError(
            "Cannot build the metadata model:\n  - " + "\n  - ".join(problems)
        )
    return tuple(model)


# --------------------------------------------------------------------------- export


def _datasets_json(model: tuple[DatasetMeta, ...]) -> str:
    """Canonical serialisation of the records alone — what the digest covers."""
    return json.dumps(
        [m.to_dict() for m in sorted(model, key=lambda m: m.dataset_id)],
        sort_keys=True,
        ensure_ascii=False,
        separators=(",", ":"),
    )


def content_digest(model: tuple[DatasetMeta, ...]) -> str:
    """``sha256:<hex>`` over the canonical JSON of the records.

    Two builds agree iff their sources describe the same datasets; the
    timestamp and schema version are deliberately outside the hash.
    """
    return "sha256:" + hashlib.sha256(_datasets_json(model).encode("utf-8")).hexdigest()


def to_json(model: tuple[DatasetMeta, ...], built_at: str | None = None) -> str:
    """Serialise the model with its envelope (schema version, digest, timestamp).

    Keys are sorted and non-ASCII is kept as-is, so the output is stable across
    builds when the sources are; ``built_at`` defaults to now in UTC.
    """
    document = {
        "schema_version": SCHEMA_VERSION,
        "content_digest": content_digest(model),
        "built_at": built_at or datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "datasets": json.loads(_datasets_json(model)),
    }
    return json.dumps(document, sort_keys=True, ensure_ascii=False, indent=1) + "\n"


def read_digest(path: Path | str = DEFAULT_JSON_PATH) -> str | None:
    """The ``content_digest`` recorded in an export, or ``None`` if unreadable."""
    try:
        with Path(path).open(encoding="utf-8") as fh:
            return json.load(fh).get("content_digest")
    except (OSError, ValueError):
        return None


def write_json(
    path: Path | str = DEFAULT_JSON_PATH, model: tuple[DatasetMeta, ...] | None = None
) -> bool:
    """Write the export to ``path``, unless the file already has the same digest.

    Leaving an unchanged file alone keeps the committed copy free of
    timestamp-only churn.

    Returns:
        ``True`` if the file was written, ``False`` if it was already current.
    """
    model = build_model() if model is None else model
    target = Path(path)
    if target.exists() and read_digest(target) == content_digest(model):
        return False
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(to_json(model), encoding="utf-8")
    return True


def load_json(path: Path | str = DEFAULT_JSON_PATH) -> tuple[DatasetMeta, ...]:
    """Read an export back into ``DatasetMeta`` records.

    Raises:
        ValueError: the file's ``schema_version`` is not the one this package
            reads, naming both.
    """
    with Path(path).open(encoding="utf-8") as fh:
        document = json.load(fh)
    version = document.get("schema_version")
    if version != SCHEMA_VERSION:
        raise ValueError(
            f"{path}: schema_version {version!r} is not readable by this ecgbench "
            f"(expects {SCHEMA_VERSION}); rebuild it with `ecgbench metadata build` "
            "or install a matching version"
        )
    return tuple(DatasetMeta.from_dict(d) for d in document["datasets"])


