"""Compile the catalogue front matter and the YAML configs into ``DatasetMeta`` records.

The sources stay the truth — humans edit ``docs/_datasets/*.md`` and
``ecgbench/data/configs/*.yaml`` — and this module derives from them. Nothing
here is hand-edited: ``ecgbench/data/metadata.json`` is regenerated by
``write_json`` and the tests compare its digest against a fresh build so it
cannot drift silently.

Merging rules, in one place:

- ``dataset_id`` is the config slug when the catalogue entry declares
  ``config_slug``, else the catalogue slug.
- Every sourced value is kept as a ``Fact``; when two sources give the same key
  the top-level field takes the winner under ``SOURCE_PRECEDENCE`` (config beats
  catalogue). The exception is ``name``, which is the catalogue's curated display
  name; a differing config name becomes an alias.
- ``records`` and ``patients`` are parsed from the catalogue display strings only
  when the whole string is a plain integer with optional thousands separators
  (``"18,869"`` → 18869). ``"~1,000"``, ``"—"``, ``"5,749 segments"`` and
  ``"25 (23 with signals)"`` give ``None`` and keep their display string; each
  unparsed value is logged once.
- Label availability is read from the presence of ``ecgbench/labels/<slug>.py``
  or a declarative ``labels:`` block naming a source CSV and join column, never
  by importing the loaders — the build must not pull in pandas. A test pins that
  file set to ``_custom_loaders()``.

Validation problems are collected and raised together as ``MetadataBuildError``,
the same pattern ``catalogue._load`` uses for ``related`` blocks.
"""

